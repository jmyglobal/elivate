try { if (localStorage.getItem('elivate.language') === 'en') language = 'en'; } catch {}
const inEnglish = () => language === 'en';
const localize = (ko, en) => inEnglish() ? en : ko;
const copyBindings = [];
const localizedAttributes = ['aria-label', 'alt', 'data-label', 'title', 'content'];
function registerCopy(root) {
  const text = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (text.nextNode()) {
    const node = text.currentNode;
    if (node.parentElement?.closest('style,script,title')) continue;
    const original = node.data;
    const english = englishCopy[original.trim().replace(/\s+/g, ' ')];
    if (english !== undefined) {
      copyBindings.push(() => { node.data = localize(original, original.replace(/\S[\s\S]*\S|\S/, () => english)); });
    }
  }
  for (const element of root.querySelectorAll('*')) {
    for (const attr of localizedAttributes) {
      const original = element.getAttribute(attr);
      const english = original && englishCopy[original.trim().replace(/\s+/g, ' ')];
      if (english) copyBindings.push(() => element.setAttribute(attr, localize(original, english)));
    }
  }
}
function applyCopy() {
  document.documentElement.lang = language;
  document.getElementById('detail-host').lang = language;
  const selector = document.getElementById('site-language');
  selector.setAttribute('aria-label', localize('언어 선택', 'Choose language'));
  const film = document.getElementById('detail-host').shadowRoot.querySelector('.product-intro-film');
  if (film.textTracks.length) film.textTracks[0].mode = inEnglish() ? 'showing' : 'disabled';
  for (const bind of copyBindings) bind();
  for (const button of selector.querySelectorAll('button[data-lang]')) {
    button.setAttribute('aria-pressed', String(button.dataset.lang === language));
  }
}
